package org.corpsman.auth.model;

/**
 * Роли пользователей закрытого клуба.
 */
public enum UserRole {

    /**
     * Гость: ограниченный доступ (форум-гостевые треды, вишлисты).
     */
    GUEST,

    /**
     * Резидент: полноправный участник клуба.
     */
    RESIDENT,

    /**
     * Мастер: администратор клуба.
     */
    MASTER
}
