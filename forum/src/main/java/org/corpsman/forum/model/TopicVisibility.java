package org.corpsman.forum.model;

/**
 * Видимость треда форума.
 */
public enum TopicVisibility {

    /**
     * Публичный: виден всем пользователям и выводится на главной.
     */
    PUBLIC,

    /**
     * Открытый: виден резидентам и мастерам (гостям скрыт).
     */
    OPEN,

    /**
     * Гостевой: как открытый, но гости могут писать и модерировать.
     */
    GUEST,

    /**
     * Закрытый: виден только владельцу, администраторам и белому списку.
     */
    CLOSED
}
